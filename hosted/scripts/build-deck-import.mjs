/**
 * Build the D1 import SQL for owner-reviewed Starter Deck bundles.
 *
 * Reads the versioned deck manifests produced by vocab/scripts/publish_decks.py
 * and emits INSERT OR IGNORE statements for the hosted learner tables
 * (migrations 0005_starter_decks.sql). Publication discipline:
 *
 *   - only manifests with status "published" are emitted; drafts are skipped
 *     with a notice, so a draft bundle can never reach learner storage;
 *   - a published manifest whose cards file or manifest hash does not verify
 *     is a hard error: nothing is emitted and the run exits non-zero;
 *   - only the reviewed learner-facing card fields are inserted — manifest
 *     provenance (source path/hash, extraction, source_ref, review status,
 *     audio) is dropped here and never reaches a learner payload;
 *   - re-running against the same bundle is an idempotent no-op, and card
 *     rows are emitted before the version row so a partially applied run can
 *     never expose a half-imported version.
 *
 * Usage: node scripts/build-deck-import.mjs [manifestDir] [outFile]
 * Then:  wrangler d1 execute <DB> --file=<outFile> [--remote]
 */
import { createHash } from "node:crypto";
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));
const DEFAULT_MANIFEST_DIR = resolve(SCRIPT_DIR, "..", "..", "vocab", "manifests");

/** English UI titles for known deck ids; content itself stays unstated chrome. */
const DECK_TITLES = {
  anki_starter: "Anki starter: SAT words",
  b2c1_1000: "B2-C1 SAT vocabulary (1,000 words)",
  c1c2_wic500: "C1-C2 word-in-context vocabulary (500 words)",
};

const CARD_COLUMNS = [
  "stable_id", "front", "part_of_speech", "ipa", "meaning_vi",
  "definition_en", "synonyms", "example_en", "example_vi", "cefr",
];

/**
 * Byte-compatible with the manifest hash format produced by
 * vocab/scripts/publish_decks.py: Python json.dumps(obj, ensure_ascii=False,
 * sort_keys=True), whose default separators are ", " and ": ".
 */
export function canonicalJson(value) {
  if (Array.isArray(value)) return `[${value.map(canonicalJson).join(", ")}]`;
  if (value && typeof value === "object") {
    const keys = Object.keys(value).sort();
    return `{${keys.map((key) => `${JSON.stringify(key)}: ${canonicalJson(value[key])}`).join(", ")}}`;
  }
  return JSON.stringify(value);
}

export function sha256Hex(text) {
  return createHash("sha256").update(text, "utf8").digest("hex");
}

function sqlText(value) {
  return `'${String(value).replace(/'/g, "''")}'`;
}

function verifyManifest(manifest, cards) {
  const problems = [];
  const body = { ...manifest };
  delete body.manifest_sha256;
  if (sha256Hex(canonicalJson(body)) !== manifest.manifest_sha256)
    problems.push("manifest_sha256 does not match the manifest body");
  if (cards === null) {
    problems.push(`cards file ${manifest.cards_file} is missing or unreadable`);
  } else {
    if (sha256Hex(canonicalJson(cards)) !== manifest.cards_sha256)
      problems.push("cards_sha256 does not match the cards file (tampering or truncation)");
    if (!cards.every((card) => card.review_status === "approved"))
      problems.push("some card rows are not owner-approved");
    if (Array.isArray(cards) && manifest.card_count !== undefined && cards.length !== manifest.card_count)
      problems.push(`cards file holds ${cards.length} rows but the manifest declares card_count ${manifest.card_count}`);
  }
  if (manifest.status !== "published")
    problems.push(`status is ${manifest.status}, not published`);
  return problems;
}

export function buildImportSql(manifestDir = DEFAULT_MANIFEST_DIR, { now = new Date().toISOString() } = {}) {
  const lines = [
    "-- Generated by hosted/scripts/build-deck-import.mjs from owner-reviewed deck manifests.",
    `-- Source bundle reviewed and published 2026-09-26; generated ${now}.`,
    "-- Idempotent: safe to re-run against the same bundle.",
  ];
  const imported = [];
  const skipped = [];
  for (const name of listManifests(manifestDir)) {
    const manifest = JSON.parse(readFileSync(join(manifestDir, name), "utf8"));
    const deckId = manifest.deck_id;
    let cards = null;
    try {
      cards = JSON.parse(readFileSync(join(manifestDir, manifest.cards_file), "utf8"));
    } catch {
      cards = null;
    }
    const problems = verifyManifest(manifest, cards);
    if (problems.length > 0 && manifest.status === "published") {
      throw new Error(`Refusing deck ${deckId}: ${problems.join("; ")}`);
    }
    if (problems.length > 0) {
      skipped.push({ deck: deckId, version: manifest.version, status: manifest.status, reason: problems.join("; ") });
      continue;
    }
    lines.push(`-- ${deckId} v${manifest.version} (${cards.length} cards, manifest ${manifest.manifest_sha256.slice(0, 12)}...)`);
    for (const card of cards) {
      if (typeof card.stable_id !== "string" || !card.stable_id || typeof card.front !== "string" || !card.front)
        throw new Error(`Refusing deck ${deckId}: a card row is missing its stable_id or front`);
      const values = CARD_COLUMNS.map((column) => sqlText(card[column] ?? ""));
      lines.push(`INSERT OR IGNORE INTO starter_deck_cards (deck_id, version, stable_id, front, part_of_speech, ipa, meaning_vi, definition_en, synonyms, example_en, example_vi, cefr) VALUES (${sqlText(deckId)}, ${Number(manifest.version)}, ${values.join(", ")});`);
    }
    const title = DECK_TITLES[deckId] ?? deckId;
    lines.push(`INSERT OR IGNORE INTO starter_deck_versions (deck_id, version, title, status, cards_sha256, manifest_sha256, card_count, imported_at) VALUES (${sqlText(deckId)}, ${Number(manifest.version)}, ${sqlText(title)}, 'published', ${sqlText(manifest.cards_sha256)}, ${sqlText(manifest.manifest_sha256)}, ${Number(manifest.card_count)}, ${sqlText(now)});`);
    imported.push({ deck: deckId, version: manifest.version, cards: cards.length });
  }
  return { sql: lines.join("\n") + "\n", imported, skipped };
}

function listManifests(manifestDir) {
  return readdirSync(manifestDir).filter((name) => name.endsWith("-manifest.json")).sort();
}

export function main(argv) {
  const [manifestDir = DEFAULT_MANIFEST_DIR, outFile] = argv;
  const { sql, imported, skipped } = buildImportSql(manifestDir);
  for (const deck of imported)
    console.log(`import: ${deck.deck} v${deck.version} (${deck.cards} cards)`);
  for (const deck of skipped)
    console.log(`skip:   ${deck.deck} v${deck.version} (${deck.status}: ${deck.reason})`);
  if (!imported.length) {
    console.error("No published deck bundle found; nothing to import.");
    return 1;
  }
  if (outFile) {
    writeFileSync(outFile, sql, "utf8");
    console.log(`SQL written to ${outFile}`);
  } else {
    process.stdout.write(sql);
  }
  return 0;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  process.exit(main(process.argv.slice(2)));
}
